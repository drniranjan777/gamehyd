/// <summary>
/// Time-to-kill for the whole roster (current balance version; hip fire), generated into docs/balance/TTK.md. The doc must match the
/// catalog: after changing balance, regenerate with UPDATE_DOCS=1 dotnet test ... and review the diff.
/// </summary>
public class TimeToKillTests
{
    private static readonly float[] Distances = { 5, 15, 30, 60, 120, 250 };

    /// <summary>Shots to kill and seconds to kill with every shot landing (shotgun: estimated pellet share).</summary>
    public static (int Shots, double Seconds)? Ttk(WeaponDefinition w, float distance, float armor, bool headshots)
    {
        if (distance > w.Range) return null;
        float pelletsHitting = w.Pellets <= 1 ? 1 : w.Pellets * PelletShare(w, distance);
        float perShot = w.DamageAt(distance) * (headshots ? w.HeadshotMultiplier : 1f) * pelletsHitting;
        if (perShot <= 0.01f) return null;
        float hp = GameRules.MaxHealth, a = armor;
        int shots = 0;
        while (hp > 0 && shots < 500)
        {
            float absorbed = Math.Min(a, perShot * GameRules.ArmorAbsorb);
            a -= absorbed;
            hp -= perShot - absorbed;
            shots++;
        }
        double seconds = (shots - 1) * w.FireIntervalSeconds + (shots - 1) / w.MagazineSize * w.ReloadSeconds;
        return (shots, seconds);
    }

    /// <summary>Share of a shotgun's pellets landing on a 0.8 m x 1.8 m body at this distance (cone vs body area).</summary>
    private static float PelletShare(WeaponDefinition w, float distance)
    {
        double coneRadius = distance * Math.Tan(w.SpreadDegrees * Math.PI / 180);
        double cone = Math.PI * coneRadius * coneRadius;
        return (float)Math.Min(1.0, 0.8 * 1.8 / Math.Max(cone, 1e-6));
    }

    public static string Report()
    {
        var sb = new StringBuilder();
        var inv = CultureInfo.InvariantCulture;
        sb.AppendLine("# Time to kill — weapon balance v" + WeaponCatalog.BalanceVersion);
        sb.AppendLine();
        sb.AppendLine("Generated by `TimeToKillTests` from `WeaponCatalog`; do not edit by hand (`UPDATE_DOCS=1 dotnet test` regenerates it).");
        sb.AppendLine("Every shot is assumed to land (shotgun: estimated share of 8 pellets hitting a 0.8 × 1.8 m body). Cells are");
        sb.AppendLine("`shots / seconds` against 100 health; reloads are included when a magazine runs out; `—` = out of range.");
        void Table(string title, float armor, bool head)
        {
            sb.AppendLine();
            sb.AppendLine($"## {title}");
            sb.AppendLine();
            sb.AppendLine("| Weapon | " + string.Join(" | ", Distances.Select(d => $"{d:0} m")) + " |");
            sb.AppendLine("|---|" + string.Concat(Distances.Select(_ => "---|")));
            foreach (WeaponDefinition w in WeaponCatalog.All)
            {
                IEnumerable<string> cells = Distances.Select(d => Ttk(w, d, armor, head) is { } t ? string.Format(inv, "{0} / {1:0.00}s", t.Shots, t.Seconds) : "—");
                sb.AppendLine($"| {w.DisplayName} | " + string.Join(" | ", cells) + " |");
            }
        }
        Table("Body shots, no armor", 0, false);
        Table("Body shots, 100 armor", 100, false);
        Table("Headshots, no armor", 0, true);
        return sb.ToString().Replace("\r\n", "\n");
    }

    [Fact]
    public void Ttk_doc_matches_the_catalog()
    {
        string dir = AppContext.BaseDirectory;
        while (dir != null && !Directory.Exists(Path.Combine(dir, "docs"))) dir = Path.GetDirectoryName(dir)!;
        Assert.NotNull(dir);
        string path = Path.Combine(dir!, "docs", "balance", "TTK.md");
        string fresh = Report();
        if (Environment.GetEnvironmentVariable("UPDATE_DOCS") == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, fresh);
        }
        Assert.True(File.Exists(path), "docs/balance/TTK.md missing: run with UPDATE_DOCS=1");
        Assert.Equal(fresh, File.ReadAllText(path).Replace("\r\n", "\n"));
    }

    [Fact]
    public void No_weapon_is_absurdly_fast_or_useless_in_its_role()
    {
        foreach (WeaponDefinition w in WeaponCatalog.All)
        {
            var armored = Ttk(w, Math.Min(15, w.Range), 100, false);
            Assert.True(armored is { Seconds: >= 0.25 }, $"{w.Id} kills a full-armor player in under 0.25 s");
            Assert.True(Ttk(w, Math.Min(15, w.Range), 0, false) is { Seconds: <= 4.0 }, $"{w.Id} takes over 4 s to kill at 15 m");
        }
        WeaponDefinition sniper = WeaponCatalog.Get(WeaponCatalog.Sniper);
        Assert.Equal(2, Ttk(sniper, 100, 0, false)!.Value.Shots);  // body: two shots
        Assert.Equal(1, Ttk(sniper, 100, 0, true)!.Value.Shots);   // head: one shot
        // Close quarters belong to the shotgun and SMG; long range to the marksman and sniper.
        double Fast(int i, float d) => Ttk(WeaponCatalog.Get(i), d, 50, false)?.Seconds ?? double.MaxValue;
        Assert.True(Fast(WeaponCatalog.Shotgun, 5) < Fast(WeaponCatalog.Rifle, 5));
        Assert.True(Fast(WeaponCatalog.Smg, 15) < Fast(WeaponCatalog.Pistol, 15));
        Assert.True(Fast(WeaponCatalog.Marksman, 120) < Fast(WeaponCatalog.Rifle, 120));
    }
}

public class MatchSimulatorTests
{
    private readonly ITestOutputHelper _out;

    public MatchSimulatorTests(ITestOutputHelper output) => _out = output;

    [Fact]
    public void Simulated_city_match_finishes_and_accounts_for_every_elimination()
    {
        MatchConfig cfg = MatchConfig.Fast(12);
        cfg.Map = CityMap.Build();
        cfg.ZoneStages = new List<ZoneStage> { new ZoneStage(5, 20, 80), new ZoneStage(5, 15, 0) };
        cfg.ZoneDamagePerSecond = 20;
        SimulatedMatch r = MatchSimulator.Run(cfg, seed: 1);
        _out.WriteLine(r.ToString());
        Assert.Equal(CompletionReason.Winner, r.Reason);
        Assert.Equal(11, r.PlayerKills + r.ZoneEliminations + r.DisconnectEliminations);
        Assert.Equal(0, r.DisconnectEliminations);
        Assert.True(r.SimulatedSecondsPerWallSecond > 5, $"simulator only {r.SimulatedSecondsPerWallSecond}x real time");
    }
}
